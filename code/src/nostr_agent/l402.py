"""L402 Lightning-gated authentication (TB3 trust boundary).

Implements L402Client (agent-side 4-step payment flow) and L402Verifier
(service-side challenge creation and 5-check verification) with identity-bound
macaroons containing BIP340 pubkeys.

Flow: GET resource -> 402 + WWW-Authenticate header -> pay invoice -> retry with token.
Runs on LND regtest (benchmarks) or testnet (network-realistic validation).
No mainnet, no production channel management.

Algorithm reference: paper Section 4 (L402 unified flow; 4-step protocol,
macaroon identifier structure, 5-check verification, caveat attenuation).
"""

