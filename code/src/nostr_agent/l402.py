def _default_caveat_checker(caveat: str) -> bool:
    """Default caveat checker for prototype.

    Accepts all recognized caveat formats. Production services should implement
    specific checkers per caveat type.

    Recognized formats:
      - "service = <domain>"
      - "capabilities ⊆ <comma-list>"
      - "expires_at < <unix-ts>"
      - "max_amount_sat ≤ <int>"
      - "request_count ≤ <int>"
      - "agent_pubkey = <hex>"
    """
    caveat = caveat.strip()

    # expires_at < <timestamp>
    if caveat.startswith("expires_at"):
        try:
            parts = caveat.split("<")
            if len(parts) == 2:
                ts = int(parts[1].strip())
                return int(time.time()) < ts
        except (ValueError, IndexError):
            pass
        return False

    # All other recognized caveats pass in the prototype.
    # service =, capabilities ⊆, max_amount_sat ≤, request_count ≤, agent_pubkey =
    recognized_prefixes = (
        "service",
        "capabilities",
        "max_amount_sat",
        "request_count",
        "agent_pubkey",
    )
    for prefix in recognized_prefixes:
        if caveat.startswith(prefix):
            return True

    # Unknown caveats fail (secure default).
    return False
